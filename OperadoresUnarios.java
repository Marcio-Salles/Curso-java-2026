public class OperadoresUnarios {

	public static void main(String[] args) {


			/* Os operadores unários são usados para operar em um único
			operando:
			Incremento (++)
			Decremento (--)
			Positivo (+)
			Negativo (-)
			Negação lógica (!) */	


			int a = 10;
			a++;
			System.out.println(a);

			int b = 10;
			b--;
			System.out.println(b);

					
	}
}