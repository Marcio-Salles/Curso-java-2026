public class OperadoresLogicos {

	public static void main(String[] args) {
		
 		int a = 10;
 		int b = 20;
 		boolean c = true;

 		System.out.println( a < b && c ); // AND os dois devem ser verdadeiros
 		System.out.println( a > b || c );// OR um ou outro precisam ser verdadeiro
 		System.out.println( !c ); // NÃO lógico

	}
}